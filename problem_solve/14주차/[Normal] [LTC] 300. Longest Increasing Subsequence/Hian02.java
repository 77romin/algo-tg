/*
문제 정의

정수 배열 nums가 주어졌을 때, 원소의 순서는 유지하면서 일부 원소를 선택하여 만들 수 있는 가장 긴 엄격하게 증가하는 부분 수열의 길이를 구하는 문제입니다.
부분 수열은 원래 배열의 순서를 유지해야 하지만 모든 원소를 연속해서 선택할 필요는 없습니다.

예를 들어 nums = [10, 9, 2, 5, 3, 7, 101, 18]이라면 [2, 3, 7, 101] 또는 [2, 3, 7, 18]과 같은 증가 부분 수열을 만들 수 있으며 최대 길이는 4입니다.
엄격하게 증가해야 하므로 같은 값은 증가한 것으로 처리하지 않습니다. 따라서 [7, 7, 7]의 LIS 길이는 1입니다.
*/


/*
접근 방법

이분 탐색을 이용한 LIS 알고리즘을 사용합니다.
tails[i] = 길이가 i + 1인 증가 부분 수열을 만들었을 때 가능한 마지막 값 중 가장 작은 값을 저장합니다.

예를 들어 tails가 [2, 3, 7, 18]이라면 다음과 같은 의미입니다.

길이 1인 증가 부분 수열의 마지막 값을 최소 2로 만들 수 있습니다.
길이 2인 증가 부분 수열의 마지막 값을 최소 3으로 만들 수 있습니다.
길이 3인 증가 부분 수열의 마지막 값을 최소 7로 만들 수 있습니다.
길이 4인 증가 부분 수열의 마지막 값을 최소 18로 만들 수 있습니다.

새로운 숫자 num이 들어오면 tails에서 num 이상인 첫 번째 위치를 찾습니다.

즉 lower_bound를 찾습니다.

1. tails의 모든 값보다 num이 크다면 현재 LIS 뒤에 num을 붙일 수 있으므로 LIS 길이가 1 증가합니다.
2. tails 안에 num 이상인 값이 있다면 그 위치를 num으로 교체합니다.

값을 교체한다고 해서 실제 LIS가 바뀌었다는 의미는 아닙니다.
같은 길이의 증가 부분 수열이라면 마지막 값이 작을수록 이후 더 많은 숫자를 붙일 가능성이 커지므로 가장 작은 마지막 값을 유지하는 것입니다.
엄격하게 증가하는 LIS이므로 "num보다 큰 첫 번째 값"이 아니라 "num 이상인 첫 번째 값"을 찾아야 합니다.

예를 들어 tails = [2, 5]이고 num = 5라면 5를 뒤에 추가해서 [2, 5, 5]로 만들 수 없습니다.
따라서 기존 5 위치를 새로운 5로 교체해야 하며 LIS 길이는 증가하지 않습니다.
*/


/*
문제 풀이
*/

class Solution {
    public int lengthOfLIS(int[] nums) {
        /*
        tails[i] = 길이가 i + 1인 증가 부분 수열의 마지막 값 중 가능한 최소값
        */
        int[] tails = new int[nums.length];

        /*
        현재까지 만들어진 LIS의 길이입니다.
        */
        int size = 0;

        /*
        nums의 숫자를 하나씩 확인합니다.
        */
        for (int num : nums) {
            /*
            tails[0] ~ tails[size - 1]에서 num 이상인 첫 번째 위치를 이분 탐색으로 찾습니다.
            */
            int left = 0;
            int right = size;

            while (left < right) {
                int mid = (left + right) / 2;
                /*
                tails[mid]가 num보다 작다면 num이 더 오른쪽에 들어가야 합니다.
                */
                if (tails[mid] < num) {
                    left = mid + 1;
                }
                /*
                tails[mid] >= num이라면 현재 위치 또는 더 왼쪽에 num이 들어갈 수 있습니다.
                */
                else {
                    right = mid;
                }
            }
            /*
            left는 num 이상인 첫 번째 값의 위치입니다.
            해당 위치의 값을 num으로 교체합니다.
            */
            tails[left] = num;
            /*
            left == size라면 num이 기존 tails의 모든 값보다 큰 경우입니다.
            따라서 새로운 길이의 증가 부분 수열을 만들 수 있으므로 size를 증가시킵니다.
            */
            if (left == size) {
                size++;
            }
        }
        /*
        tails 배열 자체가 실제 LIS를 의미하는 것은 아니지만 size는 LIS의 최대 길이와 같습니다.
        */
        return size;
    }
}


/*
시간복잡도
nums의 길이를 N이라고 하겠습니다.

N개의 숫자를 하나씩 확인하며 각 숫자마다 tails 배열에서 이분 탐색을 수행합니다.
이분 탐색은 O(log N)이므로 전체 시간복잡도는 O(N log N)입니다.

Follow up에서 요구한 O(N log N)을 만족합니다.

핵심 정리

1. tails[i]는 길이가 i + 1인 증가 부분 수열의 마지막 값 중 가장 작은 값을 저장합니다.
2. 새로운 num이 들어오면 tails에서 num 이상인 첫 번째 위치를 이분 탐색으로 찾습니다.
3. 해당 위치의 값을 num으로 교체합니다.
4. num이 tails의 모든 값보다 크다면 size를 증가시킵니다.
5. 엄격하게 증가해야 하므로 lower_bound, 즉 num 이상인 첫 번째 위치를 찾아야 합니다.
6. 최종 size가 LIS의 길이입니다.
*/
