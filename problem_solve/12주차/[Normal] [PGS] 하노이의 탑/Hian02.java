/*
문제 정의

하노이 탑에는 3개의 기둥이 있습니다. 1번 기둥에 n개의 원판이 크기가 큰 순서대로 아래에서부터 쌓여 있습니다.
목표는 1번 기둥에 있는 모든 원판을 3번 기둥으로 옮기는 것입니다.

원판을 옮길 때는 다음 조건을 만족해야 합니다.
1. 한 번에 하나의 원판만 옮길 수 있습니다.
2. 큰 원판을 작은 원판 위에 올릴 수 없습니다.

n개의 원판을 최소 횟수로 옮길 때 각 이동을 [출발 기둥, 도착 기둥] 형태로 저장하여 반환하는 문제입니다.

예를 들어 n = 2라면 1 -> 2, 1 -> 3, 2 -> 3 순서로 이동하며 결과는 [[1, 2], [1, 3], [2, 3]]입니다.
*/


/*
접근 방법

재귀를 사용해서 해결합니다.

n개의 원판을 from 기둥에서 to 기둥으로 옮긴다고 생각합니다. 가장 아래에 있는 가장 큰 원판을 바로 옮길 수는 없기 때문에 그 위에 있는 n-1개의 원판을 먼저 보조 기둥 via로 옮겨야 합니다.

따라서 다음 3단계로 해결할 수 있습니다.

1. 위의 n-1개 원판을 from -> via로 옮깁니다.
2. 가장 큰 원판 1개를 from -> to로 옮깁니다.
3. via에 있는 n-1개 원판을 via -> to로 옮깁니다.

이 과정을 재귀적으로 반복합니다.

예를 들어 hanoi(3, 1, 2, 3)은 3개의 원판을 1번 기둥에서 3번 기둥으로 옮기는 것을 의미합니다.

먼저 hanoi(2, 1, 3, 2)를 실행해서 위의 2개 원판을 2번 기둥으로 옮깁니다.
그 다음 가장 큰 원판을 1 -> 3으로 옮깁니다.
마지막으로 hanoi(2, 2, 1, 3)을 실행해서 2번 기둥에 있는 2개의 원판을 3번 기둥으로 옮깁니다.

재귀 종료 조건은 n == 1입니다. 원판이 하나라면 from -> to로 바로 이동하면 됩니다.
*/


/*
문제 풀이
*/

import java.util.*;

class Solution {
    /*
    원판의 이동 순서를 저장합니다. 각 원소는 [출발 기둥, 도착 기둥] 형태입니다.
    */
    List<int[]> moves = new ArrayList<>();
    /*
    n개의 원판을 from 기둥에서 to 기둥으로 옮깁니다. via는 보조 기둥입니다.
    */
    void hanoi(int n, int from, int via, int to) {
        /*
        원판이 하나만 남았다면 from -> to로 바로 옮기면 됩니다.
        */
        if (n == 1) {
            moves.add(new int[]{from, to});
            return;
        }
        /*
        1. 위의 n-1개 원판을 from -> via로 옮깁니다. 이때 기존 목적지였던 to가 보조 기둥 역할을 합니다.
        */
        hanoi(n - 1, from, to, via);
        /*
        2. 가장 큰 원판을 from -> to로 옮깁니다.
        */
        moves.add(new int[]{from, to});
        /*
        3. via에 있는 n-1개의 원판을 via -> to로 옮깁니다. 이때 기존 출발지였던 from이 보조 기둥 역할을 합니다.
        */
        hanoi(n - 1, via, from, to);
    }

    public int[][] solution(int n) {
        /*
        solution이 여러 번 호출될 수 있으므로 기존 이동 기록을 초기화합니다.
        */
        moves.clear();
        /*
        n개의 원판을 1번 기둥에서 3번 기둥으로 옮깁니다. 2번 기둥은 보조 기둥입니다.
        */
        hanoi(n, 1, 2, 3);
        /*
        List<int[]>를 배열로 변환합니다.
        */
        int[][] answer = new int[moves.size()][2];

        for (int i = 0; i < moves.size(); i++) {
            answer[i][0] = moves.get(i)[0];
            answer[i][1] = moves.get(i)[1];
        }

        return answer;
    }
}


/*
시간복잡도

하노이 탑에서 n개의 원판을 옮기는 최소 이동 횟수를 T(n)이라고 하면 T(n) = 2 * T(n - 1) + 1입니다.

n-1개의 원판을 보조 기둥으로 옮기고, 가장 큰 원판을 한 번 옮긴 뒤, 다시 n-1개의 원판을 목적지로 옮겨야 하기 때문입니다.

이를 계산하면 T(n) = 2^n - 1이므로 시간복잡도는 O(2^n)입니다.

n <= 15이므로 최대 이동 횟수는 2^15 - 1 = 32767번이며 충분히 처리할 수 있습니다.

공간복잡도

모든 이동 순서를 저장해야 하므로 O(2^n)입니다.
재귀 호출 깊이는 최대 n이므로 재귀 스택은 O(n)입니다.

핵심 정리

1. n개의 원판 중 위의 n-1개를 보조 기둥으로 옮깁니다.
2. 가장 큰 원판을 목적지로 옮깁니다.
3. 보조 기둥에 있는 n-1개의 원판을 목적지로 옮깁니다.
4. 이 과정을 재귀적으로 반복합니다.
5. 최소 이동 횟수는 2^n - 1입니다.
*/
